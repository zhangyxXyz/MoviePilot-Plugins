const { createRequire } = require('node:module');
const pluginRequire = createRequire(require('node:path').resolve(__dirname, '../../../plugins.v3/torrentcleanup/package.json'));
const { chromium } = pluginRequire('playwright');
const path = require('node:path');
const projectRoot = process.env.TORRENTCLEANUP_SCREENSHOTS || require('node:fs').mkdtempSync(path.join(require('node:os').tmpdir(), 'torrentcleanup-ui-'));
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 page.setDefaultTimeout(10000); const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 page.on('console', m=>{ if(m.type()==='error') errors.push(m.text()) });
 await page.goto('http://127.0.0.1:5177/preview.html');
 await page.getByRole('heading',{name:'种子清理'}).waitFor(); console.log('loaded');
 await page.waitForTimeout(450);
 await page.screenshot({path:path.join(projectRoot, 'preview-desktop.png'),fullPage:true});
 if(await page.getByRole('button',{name:'执行本次计划'}).isEnabled()) throw Error('Disabled global execution must block action');
 await page.getByRole('button',{name:'编辑',exact:true}).click();
 await page.getByLabel('任务名称').fill('CarPT · 测试保存');
 await page.getByRole('tab',{name:'清理条件'}).click();
 await page.waitForTimeout(450);
 await page.screenshot({path:path.join(projectRoot, 'preview-editor.png'),fullPage:true});
 await page.getByRole('button',{name:'保存任务'}).click(); console.log('save clicked');
 await page.getByRole('heading',{name:'CarPT · 测试保存'}).waitFor();
 await page.getByRole('button',{name:'站点与保护'}).click();
 await page.getByRole('button',{name:/CarPT.*保种要求待配置/}).click();
 await page.getByRole('button',{name:'保存',exact:true}).click();
 await page.getByRole('button',{name:'站点与保护'}).waitFor();
 await page.setViewportSize({width:390,height:844});
 await page.waitForTimeout(450);
 await page.screenshot({path:path.join(projectRoot, 'preview-mobile.png'),fullPage:true});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 console.log(JSON.stringify({errors,mobileOverflow:overflow,checks:['preview','disabled execution','edit task','save task','edit settings','save settings','mobile']}));
 await browser.close();
 if(errors.length||overflow) process.exit(1);
})().catch(e=>{console.error(e);process.exit(1)});
